/* 餐次类兜底词：只有在句中找不到具体食物时才使用 */
const FALLBACK_WORDS = new Set([
  '早餐','早饭','午餐','午饭','晚餐','晚饭','夜宵','宵夜','外卖','食堂','聚餐','下午茶','快餐',
]);

/* —— 中文数字 —— */
const CN_DIGIT = { 零:0, 一:1, 两:2, 二:2, 三:3, 四:4, 五:5, 六:6, 七:7, 八:8, 九:9, 半:0.5 };

function cnToNum(s) {
  if (!s) return null;
  if (/^\d+(\.\d+)?$/.test(s)) return Number(s);
  if (s === '十') return 10;
  if (/^十[一二三四五六七八九]$/.test(s)) return 10 + CN_DIGIT[s[1]];
  if (/^[一二两三四五六七八九]十$/.test(s)) return CN_DIGIT[s[0]] * 10;
  if (/^[一二两三四五六七八九]十[一二三四五六七八九]$/.test(s)) return CN_DIGIT[s[0]] * 10 + CN_DIGIT[s[2]];
  if (s.length === 1 && CN_DIGIT[s] != null) return CN_DIGIT[s];
  return null;
}

/* 量词表：用于「两个」「一碗」「3 串」这类前缀 */
const UNIT_RE = '个|颗|根|条|碗|杯|份|块|只|片|袋|瓶|罐|串|盒|支|两|斤|顿|口|勺|包';

/** 从食物名前方回看，抽取数量（找不到按 1 计） */
function pickQty(src, idx) {
  const head = src.slice(Math.max(0, idx - 6), idx);
  const m = head.match(new RegExp(`(\\d+(?:\\.\\d+)?|[零一二两三四五六七八九十半]{1,3})\\s*(?:${UNIT_RE})?\\s*$`));
  if (!m) return 1;
  const n = cnToNum(m[1]);
  if (n == null || n <= 0) return 1;
  // 防呆：超过 30 份多半是误抓到年份/金额
  return n > 30 ? 1 : n;
}

/**
 * 从原句抽取食物明细
 * @returns {{name:string, qty:number, unit:string, per:number, kcal:number}[]}
 */
export function parseFoods(text) {
  const src = String(text || '');
  if (!src) return [];

  const taken = new Array(src.length).fill(false);
  const hits = [];
  const names = Object.keys(FOOD_DB).sort((a, b) => b.length - a.length);

  for (const name of names) {
    let idx = src.indexOf(name);
    while (idx >= 0) {
      let overlap = false;
      for (let i = idx; i < idx + name.length; i++) if (taken[i]) { overlap = true; break; }
      if (!overlap) {
        for (let i = idx; i < idx + name.length; i++) taken[i] = true;
        const [per, unit] = FOOD_DB[name];
        const qty = pickQty(src, idx);
        hits.push({ name, qty, unit, per, kcal: Math.round(per * qty), at: idx, fallback: FALLBACK_WORDS.has(name) });
      }
      idx = src.indexOf(name, idx + name.length);
    }
  }

  if (!hits.length) return [];

  // 有具体食物时，丢掉「午餐」这类兜底词，避免重复计
  const real = hits.filter(x => !x.fallback);
  const use = real.length ? real : hits;

  return use
    .sort((a, b) => a.at - b.at)
    .map(({ name, qty, unit, per, kcal }) => ({ name, qty, unit, per, kcal }));
}

/** 估算整句总热量（无法识别返回 null，交给用户手填） */
export function estimateKcal(text) {
  const foods = parseFoods(text);
  if (!foods.length) return null;
  const sum = foods.reduce((a, f) => a + f.kcal, 0);
  return sum > 0 ? sum : null;
}

/** 食物明细求和 */
export const sumFoods = (foods) =>
  (foods || []).reduce((a, f) => a + (+f.kcal || 0), 0);

/** 明细摘要文案：两个鸡蛋 · 一杯豆浆 */
export function foodsSummary(foods) {
  if (!foods || !foods.length) return null;
  return foods.map(f => (f.qty > 1 ? `${f.qty}${f.unit || ''}${f.name}` : f.name)).join(' · ');
}

/** 这条记录算不算「吃喝」（餐食视图的唯一口径） */
export function isMeal(rec) {
  return rec && rec.type === 'ledger' && !rec.isIncome && rec.category === '餐饮';
}

/** 取一条记录的最终热量：手填优先，其次明细求和 */
export function recKcal(rec) {
  if (!rec) return 0;
  if (rec.kcal != null && rec.kcal !== '') return +rec.kcal || 0;
  return sumFoods(rec.foods);
}

/** 把「鸡蛋 78」这种多行文本解析回明细数组（结果页手改用） */
export function parseFoodLines(text) {
  return String(text || '')
    .split('\n')
    .map(line => line.trim())
    .filter(Boolean)
    .map(line => {
      const m = line.match(/^(.+?)[\s:：]+(\d+(?:\.\d+)?)\s*(?:kcal|千卡|大卡)?$/i);
      if (m) return { name: m[1].trim(), qty: 1, unit: '份', per: Math.round(+m[2]), kcal: Math.round(+m[2]) };
      // 没写热量的行 → 尝试用食物库估
      const est = estimateKcal(line);
      return { name: line, qty: 1, unit: '份', per: est || 0, kcal: est || 0 };
    });
}

/** 明细数组 → 可编辑文本 */
export const foodsToLines = (foods) =>
  (foods || []).map(f => `${f.qty > 1 ? f.qty + (f.unit || '') : ''}${f.name} ${f.kcal}`).join('\n');
